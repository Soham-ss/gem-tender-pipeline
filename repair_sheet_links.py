#!/usr/bin/env python3
"""
Retroactive Bid Document Link Repair Utility
Audits Google Sheet tender rows and replaces invalid or string-constructed
bid document URLs with authentic live URLs dynamically extracted from GeM DOM.
"""

import argparse
import logging
import re
import sys
import time
from typing import List, Dict, Any, Optional
from playwright.sync_api import sync_playwright

import config
from gem_scraper import get_authentic_bid_document_url
from sheets_manager import GoogleSheetsManager

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(config.BASE_DIR / "link_repair.log", encoding="utf-8")
    ]
)
logger = logging.getLogger("link_repair")

def is_naive_or_invalid_url(url: str, gem_id: str) -> bool:
    """
    Identifies whether a URL was naively generated by string-concatenating GeM ID digits,
    or is empty / Not Found / invalid.
    """
    if not url or url.strip() in ("", "Not Found", "#"):
        return True

    # Check if URL ends with the exact numeric suffix of the GeM ID (the naive string pattern)
    gem_num_match = re.search(r"(\d+)$", gem_id.strip())
    if gem_num_match:
        gem_num = gem_num_match.group(1)
        if url.strip().endswith(f"showbidDocument/{gem_num}"):
            return True

    return False

class RetroactiveLinkRepairer:
    """
    Automates link repair across existing Google Sheet records.
    """

    def __init__(self, dry_run: bool = False, headless: bool = config.HEADLESS):
        self.dry_run = dry_run
        self.headless = headless
        self.sheets_manager: Optional[GoogleSheetsManager] = None
        self._init_sheets()

    def _init_sheets(self) -> None:
        try:
            self.sheets_manager = GoogleSheetsManager()
            logger.info("Connected to Google Sheets via Service Account.")
        except Exception as e:
            logger.warning(f"Google Sheets Service Account unavailable ({e}). Running in inspection mode.")

    def repair_links(self, specific_ids: Optional[List[str]] = None, limit: Optional[int] = None) -> None:
        """
        Scans Google Sheet rows, locates invalid URLs, extracts authentic URLs via Playwright DOM,
        and updates the Google Sheet cells.
        """
        logger.info("\n" + "=" * 60)
        logger.info("STARTING RETROACTIVE BID DOCUMENT LINK REPAIR")
        logger.info(f"Mode: {'DRY RUN' if self.dry_run else 'LIVE SHEET UPDATE'}")
        logger.info(f"Headless: {self.headless}")
        logger.info("=" * 60 + "\n")

        targets: List[Dict[str, Any]] = []

        if specific_ids:
            for idx, gid in enumerate(specific_ids, start=1):
                targets.append({
                    "row_idx": idx,
                    "gem_id": gid.strip(),
                    "source_url": "Manual Target"
                })
        elif self.sheets_manager:
            rows = self.sheets_manager.get_all_rows_with_gem_ids()
            logger.info(f"Fetched {len(rows)} records from Google Sheet.")
            for r in rows:
                gid = r.get("gem_id", "")
                curr_url = r.get("source_url", "")
                if is_naive_or_invalid_url(curr_url, gid):
                    targets.append(r)
            logger.info(f"Found {len(targets)} rows with naive, invalid, or missing URLs requiring repair.")
        else:
            logger.error("No Google Sheets connection or target GeM IDs provided. Exiting.")
            return

        if limit and limit > 0:
            targets = targets[:limit]
            logger.info(f"Limited processing to first {len(targets)} rows.")

        if not targets:
            logger.info("All tender records already contain valid or verified URLs. No repairs needed.")
            return

        repaired_count = 0
        failed_count = 0

        with sync_playwright() as p:
            browser = p.chromium.launch(
                headless=self.headless,
                args=[
                    "--no-sandbox",
                    "--disable-setuid-sandbox",
                    "--disable-blink-features=AutomationControlled",
                    "--disable-dev-shm-usage"
                ]
            )
            context = browser.new_context(
                user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
                viewport={"width": 1280, "height": 800}
            )
            page = context.new_page()

            try:
                # Navigate to GeM all-bids portal once
                logger.info(f"Navigating to GeM Portal: {config.GEM_PORTAL_SEARCH_URL}")
                page.goto(config.GEM_PORTAL_SEARCH_URL, timeout=config.BROWSER_TIMEOUT_MS, wait_until="domcontentloaded")
                page.wait_for_timeout(3000)

                for item in targets:
                    row_idx = item.get("row_idx")
                    gem_id = item.get("gem_id", "")
                    old_url = item.get("source_url", "")

                    logger.info(f"\n[Processing Row {row_idx}] GeM ID: {gem_id} | Old URL: {old_url}")

                    # Extract authentic document URL strictly from DOM
                    authentic_url = get_authentic_bid_document_url(page, gem_id)

                    if authentic_url and authentic_url != "Not Found":
                        logger.info(f"[AUTHENTIC URL FOUND] Row {row_idx}: {authentic_url}")
                        if not self.dry_run and self.sheets_manager:
                            success = self.sheets_manager.update_source_url(row_idx, authentic_url, gem_id=gem_id)
                            if success:
                                repaired_count += 1
                        else:
                            logger.info(f"[DRY-RUN REPAIR] Would update row {row_idx} to: {authentic_url}")
                            repaired_count += 1
                    else:
                        logger.warning(f"[NOT FOUND ON PORTAL] Could not extract live card for: {gem_id}")
                        failed_count += 1

                    time.sleep(1.5)  # Polite crawl delay

            except Exception as e:
                logger.error(f"Error during link repair session: {e}", exc_info=True)
            finally:
                try:
                    context.close()
                    browser.close()
                except Exception:
                    pass

        logger.info("\n" + "=" * 60)
        logger.info("LINK REPAIR EXECUTION SUMMARY")
        logger.info(f"Total Rows Inspected: {len(targets)}")
        logger.info(f"Successfully Repaired: {repaired_count}")
        logger.info(f"Not Found / Unchanged: {failed_count}")
        logger.info("=" * 60)

def main():
    parser = argparse.ArgumentParser(description="Retroactive Bid Document Link Repair Utility")
    parser.add_argument("--gem-ids", nargs="+", help="Specific GeM IDs to repair", default=None)
    parser.add_argument("--limit", type=int, help="Maximum number of rows to repair", default=None)
    parser.add_argument("--dry-run", action="store_true", help="Inspect and test without writing to Google Sheets")
    parser.add_argument("--headed", action="store_true", help="Run browser in visible (headed) mode")

    args = parser.parse_args()

    repairer = RetroactiveLinkRepairer(
        dry_run=args.dry_run,
        headless=not args.headed
    )
    repairer.repair_links(specific_ids=args.gem_ids, limit=args.limit)

if __name__ == "__main__":
    main()
